export const cleanDescription = (raw: string): string => {
  if (!raw) return '';
  let cleaned = raw.replace(/^[\s"']+|[\s"']+$/g, '');
  cleaned = cleaned.replace(/\b[A-Z0-9]{6,}\b/g, ' ');
  cleaned = cleaned.replace(/\b\d{4,}\b/g, ' ');
  cleaned = cleaned.replace(/\b[A-Za-z0-9]{2,4}\*[A-Za-z0-9]+/g, ' ');
  cleaned = cleaned.replace(/\b(POS|ACH|DEBIT|CREDIT|PURCHASE|WITHDRAWAL|CHECKCARD|RECURRING|PREAUTHORIZED|PENDING|POSTED|WEB|ONLINE|MOBILE|ELECTRONIC|ORIG CO NAME|CO ENTRY|SEC|CCD|PPD|TEL|WEB ID|TRACE|IND ID|IND NAME|TFR|XFER|PMT|BIL|CHK|DDA|SAV)\b/gi, ' ');
  cleaned = cleaned.replace(/#\S+/g, ' ');
  cleaned = cleaned.replace(/\b\d{1,2}\/\d{1,2}\b/g, ' ');
  cleaned = cleaned.replace(/\*+/g, ' ');
  cleaned = cleaned.replace(/\s{2,}/g, ' ').trim();

  const knownMerchants = Object.keys(MERCHANT_CATEGORIES);
  const lowerCleaned = cleaned.toLowerCase();
  for (const merchant of knownMerchants) {
    const idx = lowerCleaned.indexOf(merchant);
    if (idx !== -1) {
      const extracted = cleaned.substring(idx, idx + merchant.length);
      const words = extracted.split(/\s+/);
      const titleCase = words.map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ');
      return titleCase;
    }
  }

  if (cleaned.length > 30) {
    const words = cleaned.split(/\s+/);
    const meaningful = words.filter(w => w.length > 1 && !/^\d+$/.test(w));
    cleaned = meaningful.slice(0, 4).join(' ');
  }

  if (cleaned.length > 0) {
    const words = cleaned.split(/\s+/);
    cleaned = words.map(w => {
      if (w.length <= 3 && w === w.toUpperCase()) return w;
      return w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
    }).join(' ');
  }

  return cleaned || 'Unknown';
};

export const categorizeTransaction = (description: string): string | undefined => {
  const lower = description.toLowerCase();
  for (const [keyword, category] of Object.entries(MERCHANT_CATEGORIES)) {
    if (lower.includes(keyword)) {
      return category;
    }
  }
  return undefined;
};

export const parseDate = (dateStr: string): string => {
  const trimmed = dateStr.trim().replace(/^"|"$/g, '');
  if (/^\d{4}-\d{2}-\d{2}$/.test(trimmed)) return trimmed;
  if (/^\d{1,2}\/\d{1,2}\/\d{4}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('/');
    return `${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  if (/^\d{1,2}\/\d{1,2}\/\d{2}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('/');
    const fullYear = parseInt(y) > 50 ? `19${y}` : `20${y}`;
    return `${fullYear}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  if (/^\d{1,2}-\d{1,2}-\d{4}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('-');
    return `${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  const parsed = new Date(trimmed);
  if (!isNaN(parsed.getTime())) {
    return parsed.toISOString().split('T')[0];
  }
  return new Date().toISOString().split('T')[0];
};

export const parseCSVLine = (line: string): string[] => {
  const fields: string[] = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (inQuotes) {
      if (char === '"' && line[i + 1] === '"') {
        current += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        current += char;
      }
    } else {
      if (char === '"') {
        inQuotes = true;
      } else if (char === ',') {
        fields.push(current.trim());
        current = '';
      } else {
        current += char;
      }
    }
  }
  fields.push(current.trim());
  return fields;
};

export const detectColumns = (headerFields: string[]): { dateCol: number; descCol: number; amountCol: number; debitCol: number; creditCol: number } => {
  let dateCol = -1;
  let descCol = -1;
  let amountCol = -1;
  let debitCol = -1;
  let creditCol = -1;

  headerFields.forEach((h, i) => {
    const lower = h.toLowerCase().replace(/["']/g, '').trim();
    if (dateCol === -1 && (lower.includes('date') || lower.includes('posted') || lower === 'trans date' || lower === 'transaction date')) {
      dateCol = i;
    } else if (lower.includes('debit') || lower === 'withdrawals' || lower === 'withdrawal') {
      debitCol = i;
    } else if (lower.includes('credit') || lower === 'deposits' || lower === 'deposit') {
      creditCol = i;
    } else if (amountCol === -1 && (lower.includes('amount') || lower === 'sum' || lower === 'value' || lower === 'total')) {
      amountCol = i;
    } else if (descCol === -1 && (lower.includes('desc') || lower.includes('memo') || lower.includes('narrative') || lower.includes('detail') || lower.includes('payee') || lower.includes('name') || lower.includes('transaction'))) {
      descCol = i;
    }
  });

  if (dateCol === -1) dateCol = 0;
  if (descCol === -1) {
    descCol = headerFields.length > 1 ? 1 : -1;
  }
  if (amountCol === -1 && debitCol === -1 && creditCol === -1) {
    amountCol = headerFields.length > 2 ? 2 : (headerFields.length > 1 ? 1 : 0);
  }

  return { dateCol, descCol, amountCol, debitCol, creditCol };
};

export interface ParsedTransaction {
  amount: number;
  description: string;
  date: string;
  type: 'income' | 'expense';
  budgetId?: number;
}

export const processCSVData = (
  text: string,
  budgets: Array<{ id: number; name: string }>,
): { imported: ParsedTransaction[]; skipped: number; errors: string[] } => {
  const lines = text.split(/\r?\n/).filter(l => l.trim().length > 0);
  console.log('Total non-empty lines:', lines.length);

  if (lines.length < 2) {
    return { imported: [], skipped: 0, errors: ['File has no data rows.'] };
  }

  const headerFields = parseCSVLine(lines[0]);
  console.log('Header fields:', headerFields);
  const cols = detectColumns(headerFields);
  console.log('Detected columns:', JSON.stringify(cols));

  const imported: ParsedTransaction[] = [];
  let skipped = 0;
  const errors: string[] = [];

  const findMatchingBudget = (category: string | undefined): number | undefined => {
    if (!category) return undefined;
    const lowerCat = category.toLowerCase();
    const match = budgets.find(b => b.name.toLowerCase() === lowerCat || b.name.toLowerCase().includes(lowerCat) || lowerCat.includes(b.name.toLowerCase()));
    return match?.id;
  };

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const parts = parseCSVLine(line);
    if (parts.length < 2) {
      skipped++;
      continue;
    }

    const dateStr = parts[cols.dateCol]?.replace(/^"|"$/g, '').trim();
    const description = cols.descCol >= 0 ? parts[cols.descCol]?.replace(/^"|"$/g, '').trim() : '';

    let amountNum = 0;
    if (cols.debitCol >= 0 || cols.creditCol >= 0) {
      const debitStr = cols.debitCol >= 0 ? parts[cols.debitCol]?.replace(/[^0-9.\-]/g, '') : '';
      const creditStr = cols.creditCol >= 0 ? parts[cols.creditCol]?.replace(/[^0-9.\-]/g, '') : '';
      const debitVal = parseFloat(debitStr || '0') || 0;
      const creditVal = parseFloat(creditStr || '0') || 0;
      if (creditVal > 0) {
        amountNum = creditVal;
      } else if (debitVal > 0) {
        amountNum = -debitVal;
      } else if (debitVal < 0) {
        amountNum = debitVal;
      }
    } else if (cols.amountCol >= 0) {
      const amountStr = parts[cols.amountCol]?.replace(/[^0-9.\-]/g, '') || '0';
      amountNum = parseFloat(amountStr);
    }

    if (!dateStr || isNaN(amountNum) || amountNum === 0) {
      skipped++;
      if (i <= 3) errors.push(`Row ${i}: date="${dateStr}" amount=${amountNum}`);
      continue;
    }

    const isExpense = amountNum < 0;
    const amount = Math.abs(amountNum);
    const date = parseDate(dateStr);

    const cleanedName = cleanDescription(description);
    const category = categorizeTransaction(description) || categorizeTransaction(cleanedName);
    const matchedBudgetId = isExpense ? findMatchingBudget(category) : undefined;

    const finalDescription = category
      ? `${cleanedName} (${category})`
      : cleanedName || (isExpense ? 'Expense' : 'Income');

    imported.push({
      amount,
      description: finalDescription,
      date,
      type: isExpense ? 'expense' : 'income',
      budgetId: matchedBudgetId,
    });
  }

  return { imported, skipped, errors };
};

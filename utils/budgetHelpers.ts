export const cleanDescription = (raw: string): string => {
  if (!raw) return '';
  let cleaned = raw.replace(/^[\s"']+|[\s"']+$/g, '');

  const knownMerchants = Object.keys(MERCHANT_CATEGORIES);
  const lowerRaw = cleaned.toLowerCase();
  for (const merchant of knownMerchants) {
    const idx = lowerRaw.indexOf(merchant);
    if (idx !== -1) {
      const endIdx = idx + merchant.length;
      const afterMerchant = cleaned.substring(endIdx).trim();
      const extraWord = afterMerchant.match(/^([A-Za-z][A-Za-z'-]+)/);
      if (extraWord && extraWord[1].length > 1 && !/^\d/.test(extraWord[1])) {
        const fullName = cleaned.substring(idx, endIdx) + ' ' + extraWord[1];
        return toTitleCase(fullName.trim());
      }
      return toTitleCase(cleaned.substring(idx, endIdx).trim());
    }
  }

  cleaned = cleaned.replace(/\b[A-Z0-9]{8,}\b/g, ' ');
  cleaned = cleaned.replace(/\b[0-9]{4,}\b/g, ' ');
  cleaned = cleaned.replace(/\b[A-Za-z0-9]{2,4}\*[A-Za-z0-9]+/g, ' ');
  cleaned = cleaned.replace(/#\S+/g, ' ');
  cleaned = cleaned.replace(/\b(POS|ACH|DEBIT|CREDIT|PURCHASE|WITHDRAWAL|CHECKCARD|RECURRING|PREAUTHORIZED|PENDING|POSTED|WEB|ONLINE|MOBILE|ELECTRONIC|ORIG CO NAME|CO ENTRY|SEC|CCD|PPD|TEL|WEB ID|TRACE|IND ID|IND NAME|TFR|XFER|PMT|BIL|CHK|DDA|SAV|INT|EXT|VISA|MASTERCARD|MC|CARD|TRANSACTION|ORIG|ENTRY|DESCR|REF|AUTH|MERCH|SQ|TST|BK|BKG|AUTOPAY|AUTO PAY|AUTO-PAY|PAYMENT|PYMT|REC|HOLD|FEE|SVC|MEMO|MISCELLANEOUS|MISC|INST|NBR|NUM|DR|CR|DB|INTERAC|INTERNET|WITHDRAWAL|DEPOSIT|WIRE|TRANSFER|FROM|TO|ACCT|ACCOUNT|CHECK|NO|EXTERNAL|INTERNAL|BRANCH|ATM|TERMINAL|LOCATION|CITY|STATE|COUNTRY|PROVINCE|CA|US|USA|TX|NY|FL|IL|OH|PA|GA|NC|MI|NJ|VA|WA|AZ|MA|TN|IN|MO|MD|WI|MN|CO|AL|SC|LA|KY|OR|OK|CT|UT|IA|NV|AR|MS|KS|NM|NE|WV|ID|HI|NH|ME|MT|RI|DE|SD|ND|AK|VT|WY|DC)\b/gi, ' ');
  cleaned = cleaned.replace(/\b\d{1,2}[/-]\d{1,2}([/-]\d{2,4})?\b/g, ' ');
  cleaned = cleaned.replace(/\*+/g, ' ');
  cleaned = cleaned.replace(/\bX{2,}\d*\b/gi, ' ');
  cleaned = cleaned.replace(/\b[A-Z]{1,3}\d{5,}\b/g, ' ');
  cleaned = cleaned.replace(/\b\d+[A-Z]+\d+\b/gi, ' ');
  cleaned = cleaned.replace(/\b[a-f0-9]{6,}\b/gi, ' ');
  cleaned = cleaned.replace(/[_-]{2,}/g, ' ');
  cleaned = cleaned.replace(/\b\d{1,3}\b/g, ' ');
  cleaned = cleaned.replace(/\b[A-Z]{2}\d{2,}\b/g, ' ');
  cleaned = cleaned.replace(/\b\d{2,}[A-Z]{2,}\b/g, ' ');
  cleaned = cleaned.replace(/\b[A-Z]\d[A-Z]\s*\d[A-Z]\d\b/g, ' ');
  cleaned = cleaned.replace(/\b\d{3,}\b/g, ' ');
  cleaned = cleaned.replace(/\s{2,}/g, ' ').trim();

  const words = cleaned.split(/\s+/).filter(w =>
    w.length > 1 &&
    !/^\d+$/.test(w) &&
    !/^[A-Z0-9]{6,}$/.test(w) &&
    !/^[0-9]+[A-Za-z]+$/.test(w) &&
    !/^[A-Za-z]+[0-9]{3,}$/.test(w)
  );

  if (words.length === 0) return 'Unknown';

  const nameWords = words.slice(0, 3).join(' ');
  return toTitleCase(nameWords);
};

const toTitleCase = (str: string): string => {
  return str.split(/\s+/).map(w => {
    if (w.length <= 3 && w === w.toUpperCase()) return w;
    return w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
  }).join(' ');
};

export const categorizeTransaction = (description: string): string | undefined => {
  const lower = description.toLowerCase();
  for (const [keyword, category] of Object.entries(MERCHANT_CATEGORIES)) {
    if (lower.includes(keyword)) {
      return category;
    }
  }
  return undefined;
};

export const detectStatementYear = (text: string): number | null => {
  const currentYear = new Date().getFullYear();
  const counts: Record<number, number> = {};
  const yearRe = /(?<![,\d])\b(20\d{2})\b(?![.\d])/g;
  let m;
  while ((m = yearRe.exec(text)) !== null) {
    const y = parseInt(m[1], 10);
    if (y >= 2010 && y <= currentYear + 1) {
      counts[y] = (counts[y] ?? 0) + 1;
    }
  }
  const entries = Object.entries(counts);
  if (entries.length === 0) return null;
  // Return the year with the most occurrences; break ties by picking the LATER year
  entries.sort((a, b) => b[1] - a[1] || parseInt(b[0]) - parseInt(a[0]));
  return parseInt(entries[0][0], 10);
};

export const detectStatementYears = (text: string): number[] => {
  const currentYear = new Date().getFullYear();
  const counts: Record<number, number> = {};
  const yearRe = /(?<![,\d])\b(20\d{2})\b(?![.\d])/g;
  let m;
  while ((m = yearRe.exec(text)) !== null) {
    const y = parseInt(m[1], 10);
    if (y >= 2010 && y <= currentYear + 1) {
      counts[y] = (counts[y] ?? 0) + 1;
    }
  }
  const entries = Object.entries(counts);
  if (entries.length === 0) return [];
  return entries.map(([yearStr]) => parseInt(yearStr, 10)).sort((a, b) => a - b);
};

export const detectStatementMonthRange = (text: string): { months: number[]; years: number[] } | null => {
  const monthNames = [
    'january', 'february', 'march', 'april', 'may', 'june',
    'july', 'august', 'september', 'october', 'november', 'december',
  ];
  const shortMonthNames = [
    'jan', 'feb', 'mar', 'apr', 'may', 'jun',
    'jul', 'aug', 'sep', 'oct', 'nov', 'dec',
  ];
  const lower = text.toLowerCase();
  const foundMonths = new Set<number>();

  for (let i = 0; i < monthNames.length; i++) {
    if (lower.includes(monthNames[i]) || lower.includes(shortMonthNames[i])) {
      foundMonths.add(i + 1);
    }
  }

  const years = detectStatementYears(text);
  if (foundMonths.size === 0 && years.length === 0) return null;

  return {
    months: [...foundMonths].sort((a, b) => a - b),
    years,
  };
};

export const inferYearMonthMap = (rawMonthNums: number[], hintYears: number[]): Map<number, number> => {
  const map = new Map<number, number>();
  const currentYear = new Date().getFullYear();
  const currentMonth = new Date().getMonth() + 1;
  const sortedMonths = [...new Set(rawMonthNums)].sort((a, b) => a - b);

  if (sortedMonths.length === 0) return map;

  const hasHighMonths = sortedMonths.some(m => m >= 10);
  const hasLowMonths = sortedMonths.some(m => m <= 3);
  const isCrossYear = hasHighMonths && hasLowMonths;

  if (hintYears.length >= 2) {
    const minYear = Math.min(...hintYears);
    const maxYear = Math.max(...hintYears);
    if (maxYear - minYear === 1 && isCrossYear) {
      for (const m of sortedMonths) {
        map.set(m, m >= 7 ? minYear : maxYear);
      }
      console.log('inferYearMonthMap: cross-year with hintYears', minYear, maxYear, '->', Object.fromEntries(map));
      return map;
    }
    for (const m of sortedMonths) {
      map.set(m, m >= 7 ? minYear : maxYear);
    }
    console.log('inferYearMonthMap: multi-year hintYears', hintYears, '->', Object.fromEntries(map));
    return map;
  }

  if (hintYears.length === 1) {
    const yr = hintYears[0];
    if (isCrossYear) {
      const currentYear = new Date().getFullYear();
      if (yr + 1 <= currentYear + 1) {
        for (const m of sortedMonths) {
          map.set(m, m >= 7 ? yr : yr + 1);
        }
        console.log('inferYearMonthMap: single hintYear cross-year, high months ->', yr, 'low months ->', yr + 1, Object.fromEntries(map));
      } else {
        for (const m of sortedMonths) {
          map.set(m, m >= 7 ? yr - 1 : yr);
        }
        console.log('inferYearMonthMap: single hintYear cross-year (yr is later), high months ->', yr - 1, 'low months ->', yr, Object.fromEntries(map));
      }
    } else {
      for (const m of sortedMonths) {
        map.set(m, yr);
      }
      console.log('inferYearMonthMap: single hintYear', yr, '->', Object.fromEntries(map));
    }
    return map;
  }

  if (isCrossYear) {
    const lateYear = currentMonth <= 6 ? currentYear - 1 : currentYear;
    const earlyYear = lateYear + 1;
    for (const m of sortedMonths) {
      map.set(m, m >= 7 ? lateYear : earlyYear);
    }
    console.log('inferYearMonthMap: cross-year inferred', lateYear, earlyYear, '->', Object.fromEntries(map));
    return map;
  }

  const bestYear = sortedMonths.every(m => m > currentMonth) ? currentYear - 1 : currentYear;
  for (const m of sortedMonths) {
    map.set(m, bestYear);
  }
  console.log('inferYearMonthMap: same-year inferred', bestYear, '->', Object.fromEntries(map));
  return map;
};

export const parseDate = (dateStr: string, hintYears?: number[], yearMonthMap?: Map<number, number>): string => {
  const trimmed = dateStr.trim().replace(/^"|"$/g, '');
  const currentYear = new Date().getFullYear();

  const safeYear = (y: number): number =>
    y >= 2000 && y <= currentYear + 1 ? y : currentYear;

  if (/^\d{4}-\d{2}-\d{2}$/.test(trimmed)) {
    const [y, m, d] = trimmed.split('-');
    return `${safeYear(parseInt(y, 10))}-${m}-${d}`;
  }
  if (/^\d{1,2}\/\d{1,2}\/\d{4}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('/');
    return `${safeYear(parseInt(y, 10))}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  if (/^\d{1,2}\/\d{1,2}\/\d{2}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('/');
    const fullYear = parseInt(y) <= 50 ? 2000 + parseInt(y) : 1900 + parseInt(y);
    return `${safeYear(fullYear)}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  if (/^\d{1,2}-\d{1,2}-\d{4}$/.test(trimmed)) {
    const [m, d, y] = trimmed.split('-');
    return `${safeYear(parseInt(y, 10))}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  if (/^\d{1,2}[/-]\d{1,2}$/.test(trimmed)) {
    const [m, d] = trimmed.split(/[/-]/);
    const monthNum = parseInt(m, 10);
    const dayNum = parseInt(d, 10);
    if (monthNum < 1 || monthNum > 12 || dayNum < 1 || dayNum > 31) {
      console.log('parseDate: invalid month/day:', monthNum, dayNum, 'from', trimmed);
      return new Date().toISOString().split('T')[0];
    }

    const mm = m.padStart(2, '0');
    const dd = d.padStart(2, '0');

    if (yearMonthMap && yearMonthMap.has(monthNum)) {
      const yr = yearMonthMap.get(monthNum)!;
      console.log('parseDate: MM/DD mapped', trimmed, '-> year', yr);
      return `${yr}-${mm}-${dd}`;
    }

    if (hintYears && hintYears.length > 0) {
      const minYear = Math.min(...hintYears);
      const maxYear = Math.max(...hintYears);

      if (hintYears.length >= 2 && maxYear - minYear === 1) {
        const chosenYear = monthNum >= 7 ? minYear : maxYear;
        console.log('parseDate: MM/DD cross-year fallback', trimmed, '-> year', chosenYear);
        return `${chosenYear}-${mm}-${dd}`;
      }

      console.log('parseDate: MM/DD hintYear fallback', trimmed, '-> year', minYear);
      return `${minYear}-${mm}-${dd}`;
    }

    console.log('parseDate: MM/DD no hints, using currentYear', trimmed, '->', currentYear);
    return `${currentYear}-${mm}-${dd}`;
  }
  if (/^[A-Za-z]+ \d{1,2}$/.test(trimmed)) {
    const yearToUse = (hintYears && hintYears.length > 0) ? hintYears[0] : currentYear;
    const parsed = new Date(`${trimmed} ${yearToUse}`);
    if (!isNaN(parsed.getTime())) {
      return `${yearToUse}-${String(parsed.getMonth() + 1).padStart(2, '0')}-${String(parsed.getDate()).padStart(2, '0')}`;
    }
  }
  const parsed = new Date(trimmed);
  if (!isNaN(parsed.getTime())) {
    const y = safeYear(parsed.getFullYear());
    return `${y}-${String(parsed.getMonth() + 1).padStart(2, '0')}-${String(parsed.getDate()).padStart(2, '0')}`;
  }
  return new Date().toISOString().split('T')[0];
};

export const parseCSVLine = (line: string): string[] => {
  const fields: string[] = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (inQuotes) {
      if (char === '"' && line[i + 1] === '"') {
        current += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        current += char;
      }
    } else {
      if (char === '"') {
        inQuotes = true;
      } else if (char === ',') {
        fields.push(current.trim());
        current = '';
      } else {
        current += char;
      }
    }
  }
  fields.push(current.trim());
  return fields;
};

export const detectColumns = (headerFields: string[]): { dateCol: number; descCol: number; amountCol: number; debitCol: number; creditCol: number } => {
  let dateCol = -1;
  let descCol = -1;
  let amountCol = -1;
  let debitCol = -1;
  let creditCol = -1;

  headerFields.forEach((h, i) => {
    const lower = h.toLowerCase().replace(/["']/g, '').trim();
    if (dateCol === -1 && (lower.includes('date') || lower.includes('posted') || lower === 'trans date' || lower === 'transaction date')) {
      dateCol = i;
    } else if (lower.includes('debit') || lower === 'withdrawals' || lower === 'withdrawal') {
      debitCol = i;
    } else if (lower.includes('credit') || lower === 'deposits' || lower === 'deposit') {
      creditCol = i;
    } else if (amountCol === -1 && (lower.includes('amount') || lower === 'sum' || lower === 'value' || lower === 'total')) {
      amountCol = i;
    } else if (descCol === -1 && (lower.includes('desc') || lower.includes('memo') || lower.includes('narrative') || lower.includes('detail') || lower.includes('payee') || lower.includes('name') || lower.includes('transaction'))) {
      descCol = i;
    }
  });

  if (dateCol === -1) dateCol = 0;
  if (descCol === -1) {
    descCol = headerFields.length > 1 ? 1 : -1;
  }
  if (amountCol === -1 && debitCol === -1 && creditCol === -1) {
    amountCol = headerFields.length > 2 ? 2 : (headerFields.length > 1 ? 1 : 0);
  }

  return { dateCol, descCol, amountCol, debitCol, creditCol };
};

